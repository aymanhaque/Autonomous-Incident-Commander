@router.post(
    "/apply",
    status_code=202,
    summary="Submit an approved Terraform remediation for execution.",
)
async def apply_remediation(
    payload: ApplyPayload,
    background_tasks: BackgroundTasks,
):
    """
    Accept an approved plan and immediately return **202 Accepted**.
    The full Terraform pipeline (init → validate → apply) runs asynchronously.
    Poll `GET /apply/{incident_id}/status` to track progress.

    The plan is supplied inline as HCL via `plan_inline`. `plan_ref` is accepted
    by the schema for forward-compatibility but is not yet resolvable.

    Idempotency: re-submitting an `incident_id` that is already `running` returns **409**.
    """
    if payload.plan_ref is not None:
        raise HTTPException(
            status_code=501,
            detail="plan_ref is not yet supported; supply the plan as raw HCL via plan_inline.",
        )

    hcl = (payload.plan_inline or "").strip()
    if len(hcl) < 10:
        raise HTTPException(
            status_code=422,
            detail="plan_inline must contain at least 10 characters of HCL.",
        )

    existing = _get_job(payload.incident_id)
    if existing and existing["status"] == "running":
        raise HTTPException(
            status_code=409,
            detail=f"Execution already in progress for incident '{payload.incident_id}'.",
        )

    _set_job(payload.incident_id, "queued", None)
    background_tasks.add_task(
        _run_pipeline_task, payload.incident_id, payload.workspace_id, hcl
    )

    logger.info(
        "Execution queued | incident=%s workspace=%s",
        payload.incident_id,
        payload.workspace_id,
    )
    return {
        "incident_id": payload.incident_id,
        "workspace_id": payload.workspace_id,
        "status": "queued",
        "message": "Terraform pipeline queued. Poll /apply/{incident_id}/status for updates.",
    }


@router.get(
    "/apply/{incident_id}/status",
    summary="Poll the execution status for a given incident.",
)
async def get_execution_status(incident_id: str):
    """
    Returns the current job record for the given incident, including:
    - `status`: queued | running | completed | failed | crashed | rolling_back | rolled_back | rollback_failed
    - `result`: the raw dict returned by the executor (stdout, stderr, failed_phase)
    - `updated_at`: ISO-8601 timestamp of the last state transition
    """
    job = _get_job(incident_id)
    if not job:
        raise HTTPException(
            status_code=404,
            detail=f"No execution record found for incident '{incident_id}'.",
        )
    return job


@router.post(
    "/rollback",
    status_code=202,
    summary="Destroy Terraform-managed resources for a completed incident.",
)
async def rollback_remediation(
    payload: RollbackPayload,
    background_tasks: BackgroundTasks,
):
    """
    Triggers `terraform destroy` against the sandbox left by a successful apply.

    **Pre-conditions:**
    - The execution for this incident must be in `completed` status.
    - The sandbox directory must still be present on disk (i.e. the apply succeeded
      and preserved the directory). In production, migrate to a remote Terraform
      backend so this constraint is lifted.
    """
    incident_id = payload.incident_id
    job = _get_job(incident_id)
    if not job:
        raise HTTPException(
            status_code=404,
            detail=f"No execution record found for incident '{incident_id}'.",
        )
    if job["status"] != "completed":
        raise HTTPException(
            status_code=409,
            detail=(
                f"Rollback is only valid for executions in 'completed' status. "
                f"Current status: '{job['status']}'."
            ),
        )

    async def _rollback_task() -> None:
        _set_job(incident_id, "rolling_back", None)
        logger.info("Rollback task started | incident=%s", incident_id)
        try:
            result = await asyncio.to_thread(executor.rollback, incident_id)
            status = "rolled_back" if result.get("success") else "rollback_failed"
            _set_job(incident_id, status, result)
            logger.info("Rollback task %s | incident=%s", status.upper(), incident_id)
        except Exception as exc:
            logger.exception("Rollback task crashed | incident=%s", incident_id)
            _set_job(incident_id, "rollback_failed", {"error": str(exc)})

    background_tasks.add_task(_rollback_task)
    return {
        "incident_id": incident_id,
        "status": "rolling_back",
        "message": f"Rollback queued. Poll /apply/{incident_id}/status for updates.",
    }
