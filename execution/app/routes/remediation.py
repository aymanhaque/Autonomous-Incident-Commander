import asyncio
import logging
import re
import threading
from datetime import datetime, timezone

from fastapi import APIRouter, BackgroundTasks, HTTPException
from pydantic import BaseModel, Field, field_validator, model_validator

from app.services.executor import executor

logger = logging.getLogger(__name__)

# No prefix: the orchestrator (n8n) and the mock contract both address this
# service at the root — POST /apply, POST /rollback, GET /apply/{id}/status.
# EXECUTION_API_URL is http://execution:8000, and n8n appends "/apply".
router = APIRouter(tags=["execution"])

# ---------------------------------------------------------------------------
# In-memory job registry
# Replace with Redis or Firestore once those services are available.
# ---------------------------------------------------------------------------
_registry: dict[str, dict] = {}
_lock = threading.Lock()

_VALID_ID = re.compile(r"^[a-zA-Z0-9_\-\.]+$")

# Default logical context when the orchestrator does not supply one. Used only
# for log correlation — it never influences the sandbox path (that is keyed off
# incident_id), so a default here is safe.
_DEFAULT_WORKSPACE = "staging-environment"


def _set_job(incident_id: str, status: str, result: dict | None) -> None:
    with _lock:
        _registry[incident_id] = {
            "incident_id": incident_id,
            "status": status,
            "result": result,
            "updated_at": datetime.now(timezone.utc).isoformat(),
        }


def _get_job(incident_id: str) -> dict | None:
    with _lock:
        return _registry.get(incident_id)


# ---------------------------------------------------------------------------
# Pydantic schemas
#
# These mirror the contract exercised by n8n's "Apply Fix" node and the
# reference mock (orchestration/mocks/mock_execution.py). The apply body carries
# the plan as `plan_inline` (raw HCL); `plan_ref` is reserved for a future
# stored-plan lookup. `workspace_id` is optional — n8n does not send it.
# ---------------------------------------------------------------------------


class ApplyPayload(BaseModel):
    incident_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique identifier for the Prometheus alert (used as sandbox directory name).",
        examples=["inc_12345", "inc-20240601-oomkill-001"],
    )
    plan_inline: str | None = Field(
        None,
        description="Raw HCL block generated by the LangGraph agent and approved by an operator.",
    )
    plan_ref: str | None = Field(
        None,
        description="Reference to a stored plan. Reserved — not yet supported by the executor.",
    )
    workspace_id: str = Field(
        _DEFAULT_WORKSPACE,
        min_length=1,
        max_length=128,
        description="Logical context label, e.g. 'staging-environment' or 'prod-us-east-1'.",
        examples=["staging-environment"],
    )

    @field_validator("incident_id")
    @classmethod
    def _no_path_traversal(cls, v: str) -> str:
        if not _VALID_ID.match(v):
            raise ValueError(
                "incident_id must contain only alphanumeric characters, hyphens, underscores, or dots."
            )
        return v

    @field_validator("workspace_id")
    @classmethod
    def _workspace_safe(cls, v: str) -> str:
        if not _VALID_ID.match(v):
            raise ValueError(
                "workspace_id must contain only alphanumeric characters, hyphens, underscores, or dots."
            )
        return v

    @model_validator(mode="after")
    def _exactly_one_plan_source(self) -> "ApplyPayload":
        # Mirrors the reference mock: supply exactly one of plan_inline / plan_ref.
        if bool(self.plan_inline) == bool(self.plan_ref):
            raise ValueError("provide exactly one of plan_inline or plan_ref.")
        return self


class RollbackPayload(BaseModel):
    incident_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Incident whose applied remediation should be torn down.",
        examples=["inc_12345"],
    )

    @field_validator("incident_id")
    @classmethod
    def _no_path_traversal(cls, v: str) -> str:
        if not _VALID_ID.match(v):
            raise ValueError(
                "incident_id must contain only alphanumeric characters, hyphens, underscores, or dots."
            )
        return v


# ---------------------------------------------------------------------------
# Background execution coroutines
# ---------------------------------------------------------------------------


async def _run_pipeline_task(incident_id: str, workspace_id: str, hcl: str) -> None:
    """Coroutine dispatched by BackgroundTasks — runs the blocking Terraform pipeline in a thread."""
    logger.info(
        "Pipeline task started | incident=%s workspace=%s",
        incident_id,
        workspace_id,
    )
    _set_job(incident_id, "running", None)

    try:
        result = await asyncio.to_thread(
            executor.run_pipeline,
            incident_id,
            workspace_id,
            hcl,
        )
        status = "completed" if result.get("success") else "failed"
        _set_job(incident_id, status, result)
        logger.info(
            "Pipeline task %s | incident=%s failed_phase=%s",
            status.upper(),
            incident_id,
            result.get("failed_phase"),
        )
    except Exception as exc:
        logger.exception("Pipeline task crashed | incident=%s", incident_id)
        _set_job(incident_id, "crashed", {"error": str(exc)})


